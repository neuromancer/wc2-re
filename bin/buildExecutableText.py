#!/usr/bin/env python3
"""Build the table that lets SDL2 read a player's German DOS WC2.EXE.

The German patch for the DOS release (wc2en2de, 2004) replaces WC2.EXE with
Origin's German build, "GE1.7F May 12 1992", along with FONTS.FNT and the
cutscene, mission and radio text. The port cannot ship that translation, but
with this table it uses the German UI text when a player has patched their own
installation.

    python3 bin/buildExecutableText.py --exe data/dos/WC2.EXE \\
        --german path/to/wc2en2de/WC2.EXE

The German build is not an in-place edit of the English one, so the two
executables' strings are aligned in order, with the strings both share as
anchors. A UI string marked with _(), N_(), C_() or NC_() gets an entry when
its German counterpart differs, formats the same printf conversions and keeps
the same [X] shortcut labels, since the port's keys stay English.

No text enters the generated header: each entry is the FNV-1a hash that
FindTranslation computes for the English string, with the offset and length of
its German counterpart. The German executable is identified by its size and the
CRC32 of its MZ header. Requires GNU xgettext.
"""
import argparse
import difflib
from pathlib import Path
import re
import sys
import tempfile
import zlib

sys.path.insert(0, str(Path(__file__).resolve().parent))
from compileTranslations import extract_ui_template, read_po  # noqa: E402

FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
CONVERSION = re.compile(rb"%[-+ #0]*(?:\*|\d+)?(?:\.(?:\*|\d+))?[hlLNF]*[a-zA-Z%]")
SHORTCUT = re.compile(rb"\[[^\]]\]")


def fnv1a(data):
    value = FNV_OFFSET
    for byte in data:
        value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


def ui_strings(root):
    with tempfile.TemporaryDirectory() as directory:
        template = Path(directory) / "ui.pot"
        template.write_text(extract_ui_template(root), encoding="utf-8")
        return sorted({entry["msgid"] for entry, *_ in read_po(template) if entry.get("msgid")})


def strings(image):
    """Printable NUL-terminated strings in file order, with their offsets."""
    found = []
    for match in re.finditer(rb"(?<=\0)[^\0]{1,400}(?=\0)", image):
        text = match.group(0)
        if all(32 <= byte < 127 or byte >= 0x80 or byte in (9, 10, 13) for byte in text):
            found.append((match.start(), text))
    return found


def header_size(image, path, parser):
    size = (image[8] | image[9] << 8) * 16
    if image[:2] != b"MZ" or not 0 < size < len(image):
        parser.error(f"{path} is not a DOS executable")
    return size


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--exe", type=Path, required=True, help="the English DOS WC2.EXE")
    parser.add_argument("--german", type=Path, required=True, help="the German WC2.EXE GE1.7F")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parent.parent / "src/sdl/executable_text.h")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    english = args.exe.read_bytes()
    german = args.german.read_bytes()
    header_size(english, args.exe, parser)
    german_header = header_size(german, args.german, parser)

    english_strings, german_strings = strings(english), strings(german)
    matcher = difflib.SequenceMatcher(None, [text for _, text in english_strings],
                                      [text for _, text in german_strings], autojunk=False)
    counterpart = {}
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag == "replace" and i2 - i1 == j2 - j1:
            counterpart.update((i1 + k, j1 + k) for k in range(i2 - i1))
    index = {offset: position for position, (offset, _) in enumerate(english_strings)}

    entries = []
    for text in ui_strings(root):
        try:
            raw = text.encode("cp437")
        except UnicodeEncodeError:
            continue
        found = english.find(b"\0" + raw + b"\0")
        position = counterpart.get(index.get(found + 1))
        if found < 0 or position is None:
            continue
        offset, translated = german_strings[position]
        if (translated == raw or len(translated) >= 65536 or
                CONVERSION.findall(translated) != CONVERSION.findall(raw) or
                sorted(SHORTCUT.findall(translated)) != sorted(SHORTCUT.findall(raw))):
            continue
        entries.append((fnv1a(raw), offset, len(translated)))
    entries.sort()

    lines = [
        "/* Generated by bin/buildExecutableText.py from the English DOS WC2.EXE and",
        " * the German WC2.EXE GE1.7F of the 2004 fan patch. Each entry is an English",
        " * UI string's FNV-1a hash, as FindTranslation computes it, with the offset",
        " * and length of its German counterpart. No text is embedded. */",
        f"#define SDL_EXECUTABLE_TEXT_FILE_SIZE {len(german)}u",
        f"#define SDL_EXECUTABLE_TEXT_HEADER_SIZE 0x{german_header:x}u",
        f"#define SDL_EXECUTABLE_TEXT_HEADER_CRC 0x{zlib.crc32(german[:german_header]):08x}u",
        "",
        "static const SdlExecutableText sdlExecutableTexts[] = {",
    ]
    lines += [f"    {{0x{value:016x}ULL, 0x{offset:05x}u, {length}u}}," for value, offset, length in entries]
    lines += ["};", ""]
    args.output.write_text("\n".join(lines), encoding="ascii")
    print(f"Wrote {len(entries)} strings to {args.output}")


if __name__ == "__main__":
    main()
