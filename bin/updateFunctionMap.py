#!/usr/bin/env python3
"""Rebuild src/map, the address-sorted list of reconstructed functions.

Every `/* Function start: 0x... */` annotation in the Win32 sources (and the
`; Function start: 0x...` lines of the assembled units) names the function
that follows it.  src/map lists them by retail address.

    bin/updateFunctionMap.py           # rewrite src/map
    bin/updateFunctionMap.py --check   # fail if src/map is stale
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, 'src', 'map')
C_MARKER = re.compile(r'/\*\s*Function start:\s*0x([0-9A-Fa-f]+)')
ASM_MARKER = re.compile(r';\s*Function start:\s*0x([0-9A-Fa-f]+)')
C_NAME = re.compile(
    r'([~A-Za-z_][A-Za-z0-9_]*(?:::[~A-Za-z_][A-Za-z0-9_]*)*)\s*\(')
ASM_NAME = re.compile(r'^(\w+)\s+proc\b')
SKIP_NAMES = {'__declspec', 'if', 'while', 'for', 'switch', 'return',
              'sizeof'}


def c_functions(path):
    lines = open(path, errors='replace').read().split('\n')
    for index, line in enumerate(lines):
        match = C_MARKER.search(line)
        if not match:
            continue
        address = int(match.group(1), 16)
        for following in lines[index + 1:index + 40]:
            stripped = following.strip()
            if (not stripped or stripped.startswith('/*') or
                    stripped.startswith('*') or stripped.startswith('#')):
                continue
            names = [n for n in C_NAME.findall(following)
                     if n not in SKIP_NAMES]
            if names:
                yield address, names[0]
                break


def asm_functions(path):
    lines = open(path, errors='replace').read().split('\n')
    for index, line in enumerate(lines):
        match = ASM_MARKER.search(line)
        if not match:
            continue
        address = int(match.group(1), 16)
        for following in lines[index + 1:index + 40]:
            name = ASM_NAME.match(following.strip())
            if name:
                yield address, name.group(1)
                break


def collect():
    entries = {}
    sources = sorted(glob.glob(os.path.join(ROOT, 'src', '*.c')) +
                     glob.glob(os.path.join(ROOT, 'src', '*.cpp')) +
                     glob.glob(os.path.join(ROOT, 'src', 'ix', '*.cpp')))
    for path in sources:
        for address, name in c_functions(path):
            entries[address] = name
    for path in sorted(glob.glob(os.path.join(ROOT, 'src', '*.asm')) +
                       glob.glob(os.path.join(ROOT, 'src', 'ix', '*.asm'))):
        for address, name in asm_functions(path):
            entries[address] = name
    return entries


def render(entries):
    lines = [
        '# Address-sorted reconstructed functions in the retail executable.',
        '# Generated by bin/updateFunctionMap.py from the source annotations.',
        '',
    ]
    for address in sorted(entries):
        lines.append(f'0x{address:08X} {entries[address]}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(collect())
    if args.check:
        current = open(OUTPUT).read() if os.path.exists(OUTPUT) else ''
        if current != text:
            print('src/map is stale; run bin/updateFunctionMap.py')
            return 1
        return 0
    with open(OUTPUT, 'w') as handle:
        handle.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
